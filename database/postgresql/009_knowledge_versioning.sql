-- ============================================================
-- Valid supersession rules
-- ============================================================

-- Supersession is coherent: superseded requires a non-null successor, assigning a
-- successor transitions the current row to superseded, and both rows must belong
-- to the same logical pack. Retirement may have no successor.
CREATE OR REPLACE FUNCTION valid_pack_version_supersession_check()
RETURNS TRIGGER AS $$
DECLARE
    successor_pack_id INTEGER;
    successor_lifecycle TEXT;
    next_id INTEGER;
    visited INTEGER[];
BEGIN
    -- Coerce lifecycle when a successor is assigned.
    IF NEW.superseded_by_version_id IS NOT NULL THEN
        NEW.lifecycle_state := 'superseded';
    END IF;

    -- Superseded must have a successor.
    IF NEW.lifecycle_state = 'superseded' AND NEW.superseded_by_version_id IS NULL THEN
        RAISE EXCEPTION 'superseded knowledge_pack_versions must specify superseded_by_version_id'
            USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.superseded_by_version_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.id = NEW.superseded_by_version_id THEN
        RAISE EXCEPTION 'knowledge_pack_versions cannot supersede itself'
            USING ERRCODE = 'check_violation';
    END IF;

    SELECT knowledge_pack_id, lifecycle_state
    INTO successor_pack_id, successor_lifecycle
    FROM knowledge_pack_versions
    WHERE id = NEW.superseded_by_version_id;

    IF successor_pack_id IS NULL THEN
        RAISE EXCEPTION 'superseded_by_version_id must reference an existing knowledge_pack_versions row'
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF successor_pack_id IS DISTINCT FROM NEW.knowledge_pack_id THEN
        RAISE EXCEPTION 'superseded_by_version_id must belong to the same knowledge_pack (%)', NEW.knowledge_pack_id
            USING ERRCODE = 'check_violation';
    END IF;

    -- A new successor must currently be published.
    IF successor_lifecycle <> 'published' THEN
        RAISE EXCEPTION 'successor knowledge_pack_versions must be published, not %', successor_lifecycle
            USING ERRCODE = 'check_violation';
    END IF;

    -- Cycle detection: follow the successor chain from the proposed successor.
    -- If it leads back to the current row, the assignment would create a cycle.
    next_id := NEW.superseded_by_version_id;
    visited := ARRAY[NEW.id];
    LOOP
        IF next_id = ANY(visited) THEN
            RAISE EXCEPTION 'supersession assignment would create a cycle involving knowledge_pack_versions %', NEW.id
                USING ERRCODE = 'check_violation';
        END IF;
        visited := array_append(visited, next_id);
        SELECT superseded_by_version_id INTO next_id
        FROM knowledge_pack_versions
        WHERE id = next_id;
        EXIT WHEN next_id IS NULL;
    END LOOP;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Supersession is coherent for template versions too: superseded requires a
-- successor, assigning a successor transitions to superseded, same template only,
-- and successor must be a valid published successor. Retirement may have no successor.
CREATE OR REPLACE FUNCTION valid_task_template_version_supersession_check()
RETURNS TRIGGER AS $$
DECLARE
    successor_template_id INTEGER;
    successor_lifecycle TEXT;
    next_id INTEGER;
    visited INTEGER[];
BEGIN
    IF NEW.superseded_by_version_id IS NOT NULL THEN
        NEW.lifecycle_state_at_publish := 'superseded';
    END IF;

    IF NEW.lifecycle_state_at_publish = 'superseded' AND NEW.superseded_by_version_id IS NULL THEN
        RAISE EXCEPTION 'superseded task_template_versions must specify superseded_by_version_id'
            USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.superseded_by_version_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.id = NEW.superseded_by_version_id THEN
        RAISE EXCEPTION 'task_template_versions cannot supersede itself'
            USING ERRCODE = 'check_violation';
    END IF;

    SELECT task_template_id, lifecycle_state_at_publish
    INTO successor_template_id, successor_lifecycle
    FROM task_template_versions
    WHERE id = NEW.superseded_by_version_id;

    IF successor_template_id IS NULL THEN
        RAISE EXCEPTION 'superseded_by_version_id must reference an existing task_template_versions row'
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF successor_template_id IS DISTINCT FROM NEW.task_template_id THEN
        RAISE EXCEPTION 'superseded_by_version_id must belong to the same task_template (%)', NEW.task_template_id
            USING ERRCODE = 'check_violation';
    END IF;

    -- A new successor must currently be published.
    IF successor_lifecycle <> 'published' THEN
        RAISE EXCEPTION 'successor task_template_versions must be published, not %', successor_lifecycle
            USING ERRCODE = 'check_violation';
    END IF;

    -- Cycle detection: follow the successor chain from the proposed successor.
    -- If it leads back to the current row, the assignment would create a cycle.
    next_id := NEW.superseded_by_version_id;
    visited := ARRAY[NEW.id];
    LOOP
        IF next_id = ANY(visited) THEN
            RAISE EXCEPTION 'supersession assignment would create a cycle involving task_template_versions %', NEW.id
                USING ERRCODE = 'check_violation';
