-- ============================================================
-- Immutability enforcement for published knowledge versions
-- ============================================================

-- Helper function: enforce that published/superseded/retired knowledge versions
-- cannot change their content. Only a single supersession/retirement metadata
-- transition is permitted from the published state.
CREATE OR REPLACE FUNCTION immutable_version_update_check()
RETURNS TRIGGER AS $$
DECLARE
    lifecycle_col TEXT;
    old_lifecycle TEXT;
    new_lifecycle TEXT;
    allowed_cols TEXT[];
    key_name TEXT;
    old_val TEXT;
    new_val TEXT;
    disallowed_changed_cols TEXT[];
BEGIN
    -- Step versions are always immutable once created because they are
    -- published together with their parent template version.
    IF TG_TABLE_NAME = 'task_template_step_versions' THEN
        RAISE EXCEPTION 'task_template_step_versions are immutable and cannot be updated'
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    -- Determine the lifecycle column name for this table.
    IF TG_TABLE_NAME = 'knowledge_pack_versions' THEN
        lifecycle_col := 'lifecycle_state';
        allowed_cols := ARRAY['superseded_by_version_id', 'effective_until', 'lifecycle_state'];
    ELSIF TG_TABLE_NAME = 'task_template_versions' THEN
        lifecycle_col := 'lifecycle_state_at_publish';
        allowed_cols := ARRAY['superseded_by_version_id', 'effective_until', 'lifecycle_state_at_publish', 'is_step_set_sealed'];
    ELSE
        RAISE EXCEPTION 'unexpected table for immutable_version_update_check: %', TG_TABLE_NAME;
    END IF;

    EXECUTE format('SELECT ($1).%I', lifecycle_col) INTO old_lifecycle USING OLD;
    EXECUTE format('SELECT ($1).%I', lifecycle_col) INTO new_lifecycle USING NEW;

    -- Once superseded or retired, no further updates of any kind are allowed.
    IF old_lifecycle IN ('superseded', 'retired') THEN
        RAISE EXCEPTION '% row is already % and cannot be updated', TG_TABLE_NAME, old_lifecycle
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    -- When published, only the single supersession/retirement transition is allowed.
    IF old_lifecycle = 'published' THEN
        FOR key_name IN
            SELECT k.key
            FROM jsonb_each(to_jsonb(OLD)) k
        LOOP
            IF key_name = ANY(allowed_cols) THEN
                CONTINUE;
            END IF;
            EXECUTE format('SELECT ($1).%I::text', key_name) INTO old_val USING OLD;
            EXECUTE format('SELECT ($1).%I::text', key_name) INTO new_val USING NEW;
            IF old_val IS DISTINCT FROM new_val THEN
                disallowed_changed_cols := array_append(disallowed_changed_cols, key_name);
            END IF;
        END LOOP;

        IF array_length(disallowed_changed_cols, 1) > 0 THEN
            RAISE EXCEPTION 'published % row is immutable; disallowed changes: %', TG_TABLE_NAME, disallowed_changed_cols
                USING ERRCODE = 'insufficient_privilege';
        END IF;

        IF new_lifecycle IS DISTINCT FROM old_lifecycle THEN
            IF new_lifecycle NOT IN ('superseded', 'retired') THEN
                RAISE EXCEPTION 'published % may only transition % to superseded or retired, not %',
                    TG_TABLE_NAME, lifecycle_col, new_lifecycle
                    USING ERRCODE = 'insufficient_privilege';
            END IF;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Helper function: block deletion of published/superseded/retired versions.
CREATE OR REPLACE FUNCTION immutable_version_delete_check()
RETURNS TRIGGER AS $$
DECLARE
    lifecycle_col TEXT;
    old_lifecycle TEXT;
BEGIN
    IF TG_TABLE_NAME = 'knowledge_pack_versions' THEN
        lifecycle_col := 'lifecycle_state';
    ELSIF TG_TABLE_NAME = 'task_template_versions' THEN
        lifecycle_col := 'lifecycle_state_at_publish';
    ELSIF TG_TABLE_NAME = 'task_template_step_versions' THEN
        RAISE EXCEPTION 'task_template_step_versions are immutable and cannot be deleted'
            USING ERRCODE = 'insufficient_privilege';
    ELSE
        RAISE EXCEPTION 'unexpected table for immutable_version_delete_check: %', TG_TABLE_NAME;
    END IF;

    EXECUTE format('SELECT ($1).%I', lifecycle_col) INTO old_lifecycle USING OLD;

    IF old_lifecycle IN ('published', 'superseded', 'retired') THEN
        RAISE EXCEPTION 'published or retired % cannot be deleted', TG_TABLE_NAME
            USING ERRCODE = 'insufficient_privilege';
    END IF;

    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

