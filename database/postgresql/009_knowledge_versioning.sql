-- Atiman Knowledge Versioning Foundation
-- Implements the first slice of ATM-013D2:
--   knowledge_packs, knowledge_pack_versions,
--   task_template_versions, task_template_step_versions.
--
-- Principles:
-- - Published versions are immutable.
-- - A task_template_version owns its complete ordered task_template_step_versions.
-- - Existing task_templates/task_template_steps remain untouched; this file only
--   creates the versioning tables that will later receive published versions.
-- - Idempotent deployment: CREATE IF NOT EXISTS / DROP IF NOT EXISTS throughout.

-- Stable identity for a knowledge pack.
CREATE TABLE IF NOT EXISTS knowledge_packs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    pack_code VARCHAR(100) NOT NULL,
    pack_name VARCHAR(255) NOT NULL,
    description TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_knowledge_packs_pack_code UNIQUE (pack_code)
);

-- Immutable published version of a knowledge pack.
CREATE TABLE IF NOT EXISTS knowledge_pack_versions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    knowledge_pack_id INTEGER NOT NULL,
    version_number VARCHAR(50) NOT NULL,
    lifecycle_state VARCHAR(50) NOT NULL DEFAULT 'draft'
        CONSTRAINT chk_knowledge_pack_versions_lifecycle_state
        CHECK (lifecycle_state IN ('draft','under_review','approved','published','superseded','retired')),
    effective_from TIMESTAMPTZ NULL,
    effective_until TIMESTAMPTZ NULL,
    superseded_by_version_id INTEGER DEFAULT NULL,
    author_user_id INTEGER DEFAULT NULL,
    reviewer_user_id INTEGER DEFAULT NULL,
    approver_user_id INTEGER DEFAULT NULL,
    reviewed_at TIMESTAMPTZ NULL,
    approved_at TIMESTAMPTZ NULL,
    published_at TIMESTAMPTZ NULL,
    next_review_at TIMESTAMPTZ NULL,
    change_summary TEXT,
    ai_assisted BOOLEAN DEFAULT FALSE,
    ai_assistance_detail JSONB DEFAULT NULL,
    created_at TIMESTAMPTZ NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_knowledge_pack_versions_pack_version UNIQUE (knowledge_pack_id, version_number),
    CONSTRAINT fk_knowledge_pack_versions_knowledge_pack
        FOREIGN KEY (knowledge_pack_id) REFERENCES knowledge_packs(id) ON DELETE CASCADE,
    CONSTRAINT fk_knowledge_pack_versions_superseded_by
        FOREIGN KEY (superseded_by_version_id) REFERENCES knowledge_pack_versions(id) ON DELETE SET NULL
);

-- Immutable published version of a task template.
-- A working task_template record may produce many versions, each frozen at publish time.
-- Task template versions are publication records: their state is published, superseded, or retired.
