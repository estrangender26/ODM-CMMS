    CONSTRAINT fk_task_template_versions_industry
        FOREIGN KEY (industry_id) REFERENCES industries(id) ON DELETE SET NULL,
    CONSTRAINT fk_task_template_versions_activity_code
        FOREIGN KEY (activity_code_id) REFERENCES activity_codes(id) ON DELETE SET NULL,
    CONSTRAINT fk_task_template_versions_parent_template
        FOREIGN KEY (parent_template_id) REFERENCES task_templates(id) ON DELETE SET NULL,
    CONSTRAINT fk_task_template_versions_published_by
        FOREIGN KEY (published_by_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_task_template_versions_superseded_by
        FOREIGN KEY (superseded_by_version_id) REFERENCES task_template_versions(id) ON DELETE SET NULL
